-- Boliche dos Amigos · lançamento por frame e tablet na pista
-- Aplicar depois de schema.sql, hardening-p0.sql, management.sql e encounters.sql.
-- A migração é aditiva: scores continua sendo a fonte compatível dos totais existentes.

begin;

create table if not exists public.score_details (
  score_id uuid primary key references public.scores(id) on delete cascade,
  game_id uuid not null references public.games(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  throws jsonb not null default '[]'::jsonb,
  pin_masks jsonb not null default '[]'::jsonb,
  updated_at timestamptz not null default now(),
  unique (game_id, player_id),
  check (jsonb_typeof(throws) = 'array'),
  check (jsonb_typeof(pin_masks) = 'array')
);

create index if not exists score_details_game_idx on public.score_details(game_id);
create index if not exists score_details_player_idx on public.score_details(player_id);

create table if not exists public.throw_changes (
  id bigint generated by default as identity primary key,
  score_id uuid not null references public.scores(id) on delete cascade,
  game_id uuid not null references public.games(id) on delete cascade,
  player_id uuid not null references public.players(id) on delete restrict,
  previous_throws jsonb not null default '[]'::jsonb,
  new_throws jsonb not null default '[]'::jsonb,
  reason text not null default 'Lançamento no tablet',
  changed_at timestamptz not null default now(),
  actor_id uuid references auth.users(id) on delete set null
);

create index if not exists throw_changes_score_idx on public.throw_changes(score_id, id desc);
create index if not exists throw_changes_game_idx on public.throw_changes(game_id, id desc);

create or replace function public.bowling_is_complete(p_throws jsonb)
returns boolean
language plpgsql
immutable
set search_path = public
as $$
declare
  rolls integer[];
  i integer := 1;
  frame integer;
  first_roll integer;
  second_roll integer;
begin
  if p_throws is null or jsonb_typeof(p_throws) <> 'array' then return false; end if;
  if jsonb_array_length(p_throws) = 0 then return false; end if;
  begin
    rolls := array(select value::integer from jsonb_array_elements_text(p_throws));
  exception when others then
    return false;
  end;
  if exists (select 1 from unnest(rolls) value where value < 0 or value > 10) then return false; end if;
  if cardinality(rolls) > 21 then return false; end if;
  for frame in 1..9 loop
    if i > cardinality(rolls) then return false; end if;
    first_roll := rolls[i];
    if first_roll = 10 then
      i := i + 1;
    else
      if i + 1 > cardinality(rolls) then return false; end if;
      second_roll := rolls[i + 1];
      if first_roll + second_roll > 10 then return false; end if;
      i := i + 2;
    end if;
  end loop;
  if i > cardinality(rolls) then return false; end if;
  first_roll := rolls[i];
  if first_roll = 10 then return cardinality(rolls) >= i + 2; end if;
  if i + 1 > cardinality(rolls) then return false; end if;
  second_roll := rolls[i + 1];
  if first_roll + second_roll > 10 then return false; end if;
  if first_roll + second_roll = 10 then return cardinality(rolls) >= i + 2; end if;
  return true;
end;
$$;

create or replace function public.bowling_total(p_throws jsonb)
returns integer
language plpgsql
immutable
set search_path = public
as $$
declare
  rolls integer[];
  i integer := 1;
  frame integer;
  first_roll integer;
  second_roll integer;
  total integer := 0;
begin
  if p_throws is null or jsonb_typeof(p_throws) <> 'array' then raise exception 'Arremessos inválidos'; end if;
  rolls := array(select value::integer from jsonb_array_elements_text(p_throws));
  if cardinality(rolls) > 21 or exists (select 1 from unnest(rolls) value where value < 0 or value > 10) then
    raise exception 'Cada arremesso deve estar entre 0 e 10';
  end if;
  if not public.bowling_is_complete(p_throws) then
    return coalesce((select sum(value) from unnest(rolls) value), 0);
  end if;
  for frame in 1..9 loop
    first_roll := rolls[i];
    if first_roll = 10 then
      total := total + 10 + rolls[i + 1] + rolls[i + 2];
      i := i + 1;
    else
      second_roll := rolls[i + 1];
      if first_roll + second_roll = 10 then total := total + 10 + rolls[i + 2];
      else total := total + first_roll + second_roll;
      end if;
      i := i + 2;
    end if;
  end loop;
  total := total + rolls[i] + rolls[i + 1] + coalesce(rolls[i + 2], 0);
  return total;
end;
$$;

create or replace function public.guard_score_detail_change()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
declare
  target_game uuid := case when tg_op = 'DELETE' then old.game_id else new.game_id end;
begin
  if not public.is_admin() then raise exception 'Acesso de administrador necessário' using errcode = '42501'; end if;
  if tg_op = 'UPDATE' and (new.score_id is distinct from old.score_id or new.game_id is distinct from old.game_id or new.player_id is distinct from old.player_id) then
    raise exception 'A identidade do detalhe de pontuação não pode mudar' using errcode = '42501';
  end if;
  if exists (
    select 1 from public.games g join public.encounters e on e.id = g.encounter_id
    where g.id = target_game and e.status = 'closed'
  ) then raise exception 'Reabra o encontro antes de alterar lançamentos' using errcode = '42501'; end if;
  if tg_op = 'DELETE' then return old; end if;
  return new;
end;
$$;

drop trigger if exists score_details_guard on public.score_details;
create trigger score_details_guard before insert or update or delete on public.score_details
for each row execute function public.guard_score_detail_change();

drop trigger if exists score_details_updated_at on public.score_details;
create trigger score_details_updated_at before update on public.score_details
for each row execute function public.set_updated_at();

alter table public.score_details enable row level security;
alter table public.throw_changes enable row level security;
drop policy if exists score_details_public_read on public.score_details;
drop policy if exists score_details_admin_write on public.score_details;
create policy score_details_public_read on public.score_details for select to anon, authenticated using (true);
create policy score_details_admin_write on public.score_details for all to authenticated using ((select public.is_admin())) with check ((select public.is_admin()));
drop policy if exists throw_changes_admin_read on public.throw_changes;
create policy throw_changes_admin_read on public.throw_changes for select to authenticated using ((select public.is_admin()));
drop policy if exists throw_changes_admin_insert on public.throw_changes;
create policy throw_changes_admin_insert on public.throw_changes for insert to authenticated with check ((select public.is_admin()));

grant select on public.score_details to anon, authenticated;
grant insert, update, delete on public.score_details to authenticated;
grant select, insert on public.throw_changes to authenticated;
grant usage, select on sequence public.throw_changes_id_seq to authenticated;

create or replace function public.save_throw_score(
  p_game_id uuid,
  p_player_id uuid,
  p_throws jsonb,
  p_pin_masks jsonb default '[]'::jsonb,
  p_finalized boolean default false,
  p_reason text default 'Lançamento no tablet'
)
returns public.scores
language plpgsql
security invoker
set search_path = public
as $$
declare
  target public.scores%rowtype;
  previous_throws jsonb := '[]'::jsonb;
  calculated_total integer;
  complete boolean;
begin
  if not public.is_admin() then raise exception 'Acesso de administrador necessário' using errcode = '42501'; end if;
  if p_throws is null or jsonb_typeof(p_throws) <> 'array' or jsonb_array_length(p_throws) > 21 then raise exception 'Arremessos inválidos'; end if;
  if p_pin_masks is null or jsonb_typeof(p_pin_masks) <> 'array' then raise exception 'Registro de pinos inválido'; end if;
  select s.* into target from public.scores s join public.games g on g.id = s.game_id where s.game_id = p_game_id and s.player_id = p_player_id for update;
  if not found then raise exception 'Jogador não vinculado à partida'; end if;
  select throws into previous_throws from public.score_details where score_id = target.id;
  complete := public.bowling_is_complete(p_throws);
  if p_finalized and not complete then raise exception 'A partida precisa dos dez frames completos'; end if;
  calculated_total := public.bowling_total(p_throws);
  update public.scores set pontos = calculated_total, finalizado = p_finalized where id = target.id returning * into target;
  insert into public.score_details(score_id, game_id, player_id, throws, pin_masks)
  values (target.id, p_game_id, p_player_id, p_throws, p_pin_masks)
  on conflict (score_id) do update set throws = excluded.throws, pin_masks = excluded.pin_masks;
  if previous_throws is distinct from p_throws then
    insert into public.throw_changes(score_id, game_id, player_id, previous_throws, new_throws, reason, actor_id)
    values (target.id, p_game_id, p_player_id, previous_throws, p_throws, left(coalesce(nullif(trim(p_reason), ''), 'Lançamento no tablet'), 160), auth.uid());
  end if;
  return target;
end;
$$;

revoke execute on function public.save_throw_score(uuid, uuid, jsonb, jsonb, boolean, text) from public, anon;
grant execute on function public.save_throw_score(uuid, uuid, jsonb, jsonb, boolean, text) to authenticated;

do $$
begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'score_details') then
    alter publication supabase_realtime add table public.score_details;
  end if;
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'throw_changes') then
    alter publication supabase_realtime add table public.throw_changes;
  end if;
end;
$$;

commit;
